const ROOT = new URL("../../", import.meta.url);

/** The `LUNABOT_` names in the code the server runs, and in what starts it (the desktop app). */
function knownOmbNames(): string[] {
  const files = execFileSync("git", ["ls-files", "server", "shared", "enterprise/server", "electron"], { cwd: ROOT, encoding: "utf8" })
    .split("\n").filter((file) => /\.(?:ts|mts|mjs|cjs|js)$/.test(file) && !/\.test\.|\/testing\/|node-test/.test(file));
  const names = new Set<string>();
  for (const file of files) for (const match of readFileSync(new URL(file, ROOT), "utf8").matchAll(/\bOMB_[A-Z0-9_]+\b/g)) names.add(match[0]);
  return [...names].sort();
}

describe("the box's environment allow-list", () => {
  it("keeps what an engine needs and drops the server's own settings and the control plane", () => {
    const kept = boxEnvironment({
      PATH: "/usr/bin", HOME: "/data", LANG: "C.UTF-8", TZ: "Europe/Berlin", LC_ALL: "C", TERM: "xterm",
      ANTHROPIC_API_KEY: "sk-ant-1", ANTHROPIC_BASE_URL: "http://127.0.0.1:18080/b/t/anthropic", CLAUDE_CONFIG_DIR: "/data/.claude",
      OPENAI_API_KEY: "sk-1", CODEX_HOME: "/data/.codex", LUNABOT_HOOK_URL: "http://127.0.0.1:8799/api/internal/hook", LUNABOT_COMMS_TOKEN: "cap",
      HTTPS_PROXY: "http://127.0.0.1:3128", NO_PROXY: "127.0.0.1", NPM_CONFIG_LOGLEVEL: "error", ELECTRON_RUN_AS_NODE: "1",
      LUNABOT_CLOUD_BOOTSTRAP_SECRET: "s", LUNABOT_CLOUD_MACHINE_ID: "m", LUNABOT_CLOUD_ADMIN_URL: "https://a", LUNABOT_LICENSE_KEY: "k",
      LUNABOT_DATA_DIR: "/data/.lunabot", LUNABOT_PORT: "8799", LUNABOT_LOOPBACK_TRUST: "owner", AWS_SECRET_ACCESS_KEY: "aws", SSH_AUTH_SOCK: "/x",
      SOME_RANDOM_NAME: "x", EMPTY: undefined,
    });
    expect(Object.keys(kept).sort()).toEqual([
      "ANTHROPIC_API_KEY", "ANTHROPIC_BASE_URL", "CLAUDE_CONFIG_DIR", "CODEX_HOME", "ELECTRON_RUN_AS_NODE", "HOME", "HTTPS_PROXY", "LANG", "LC_ALL",
      "LUNABOT_COMMS_TOKEN", "LUNABOT_HOOK_URL", "NO_PROXY", "NPM_CONFIG_LOGLEVEL", "OPENAI_API_KEY", "PATH", "TERM", "TZ",
    ]);
  });

  it("a denied name loses even against an allowing list or prefix, and the never-list beats everything", () => {
    expect(boxEnvironmentAllows("LUNABOT_COMMS_TOKEN")).toBe(true);
    expect(boxEnvironmentAllows("LUNABOT_COMMS_TOKEN", new Set(["LUNABOT_COMMS_TOKEN"]))).toBe(false);
    expect(boxEnvironmentAllows("ANTHROPIC_API_KEY", new Set(["ANTHROPIC_API_KEY"]))).toBe(false);
    expect(boxEnvironmentAllows("LUNABOT_COMPOSIO_BROKER_TOKEN")).toBe(false);
    for (const name of BOX_ENV_NEVER) expect(boxEnvironmentAllows(name), name).toBe(false);
    expect(boxEnvironmentAllows("LUNABOT_CLOUD_ANYTHING")).toBe(false);
    expect(boxEnvironmentAllows("LUNABOT_CLOUDFLARED_PATH")).toBe(false);
    expect(BOX_ENV_NAMES.has("PATH")).toBe(true);
  });

  // The CLI's session token and server address (server/headless/client.ts, scripts/mcp-server.ts): an operator may put
  // them in the server's environment, and nothing that runs in a box reads them. The engines' own LUNABOT_ keys
  // (LUNABOT_CODEX_API_KEY, LUNABOT_CHATGPT_TOKEN) still pass, and a spawn's allowEnv never lifts these two.
  it("keeps the CLI's session token and server address on the server, and the engines' LUNABOT_ keys in the box", () => {
    const kept = boxEnvironment(
      { LUNABOT_TOKEN: "omb_sess_x", LUNABOT_URL: "http://127.0.0.1:8799", LUNABOT_CODEX_API_KEY: "k", LUNABOT_CHATGPT_TOKEN: "t" },
      new Set(), new Set(["LUNABOT_TOKEN", "LUNABOT_URL"]),
    );
    expect(Object.keys(kept).sort()).toEqual(["LUNABOT_CHATGPT_TOKEN", "LUNABOT_CODEX_API_KEY"]);
  });

  it("keeps what Antigravity's runtime is started with: its harness, its file storage switch and the browser hook", () => {
    for (const name of ["ANTIGRAVITY_HARNESS_PATH", "AGY_ACP_FORCE_FILE_STORAGE", "BROWSER", "GEMINI_HOME"]) expect(boxEnvironmentAllows(name), name).toBe(true);
  });

  it("keeps the keys one spawn vouches for, under any name, past the allow-list and the deny, never past the never-list or LUNABOT_", () => {
    const deny = new Set(["OPENCODE_API_KEY", "LUNABOT_COMPOSIO_BROKER_TOKEN"]);
    const allow = new Set(["NANO_GPT_API_KEY", "OPENCODE_API_KEY", "LUNABOT_LICENSE_KEY", "LUNABOT_CLOUD_AI_TOKEN", "LUNABOT_COMPOSIO_BROKER_TOKEN"]);
    const env = { NANO_GPT_API_KEY: "n", OPENCODE_API_KEY: "o", LUNABOT_LICENSE_KEY: "l", LUNABOT_CLOUD_AI_TOKEN: "c", LUNABOT_COMPOSIO_BROKER_TOKEN: "b", DEEPSEEK_API_KEY: "d" };
    expect(boxEnvironment(env, deny, allow)).toEqual({ NANO_GPT_API_KEY: "n", OPENCODE_API_KEY: "o" });
    expect(boxEnvironment(env, deny)).toEqual({});
  });

  it("vouches only for the names the engine instance's own environment set, with its own value", () => {
    expect(instanceEnvNames({ NANO_GPT_API_KEY: "n", OPENCODE_API_KEY: "o", GONE: "g" }, { NANO_GPT_API_KEY: "n", OPENCODE_API_KEY: "server's", PATH: "/usr/bin" }))
      .toEqual(["NANO_GPT_API_KEY"]);
  });

  it("passes only the LUNABOT_ names a boxed process reads; an operator's own settings stay on the server", () => {
    const kept = boxEnvironment({
      LUNABOT_SIGNIN_SMTP_URL: "smtp://user:pass@mail.example.com", LUNABOT_SIGNIN_EMAILS: "a@example.com", LUNABOT_PHONE_SECRET_PUBLIC_KEY: "k",
      LUNABOT_TEST_INTERNAL_CAPABILITY_KEY: "k", LUNABOT_PUBLIC_URL: "https://x", LUNABOT_SOMETHING_NEW: "x", LUNABOT_EXTRA_PATH: "/opt/tools/bin",
      LUNABOT_MCP_TOKEN_BROWSER: "t", LUNABOT_GATE_CONFIG_ab12: "{}", LUNABOT_REMOTE_MCP_CONFIG_cd34: "{}", LUNABOT_HARNESS_URL: "http://127.0.0.1:8799",
    });
    expect(Object.keys(kept).sort()).toEqual(["LUNABOT_EXTRA_PATH", "LUNABOT_GATE_CONFIG_ab12", "LUNABOT_HARNESS_URL", "LUNABOT_MCP_TOKEN_BROWSER", "LUNABOT_REMOTE_MCP_CONFIG_cd34"]);
  });

  it("every LUNABOT_ name the server knows has a decision: passed to a bot's box or kept on the server", () => {
    const passed = (name: string) => BOX_ENV_LUNABOT_NAMES.has(name) || BOX_ENV_LUNABOT_PREFIXES.includes(name);
    const undecided = knownOmbNames().filter((name) => !passed(name) && !SERVER_ONLY_LUNABOT.has(name));
    expect(undecided, "add each to BOX_ENV_LUNABOT_NAMES in env.ts if a bot's engine, hook or MCP proxy reads it, else to SERVER_ONLY_LUNABOT here").toEqual([]);
    expect([...BOX_ENV_LUNABOT_NAMES].filter((name) => SERVER_ONLY_LUNABOT.has(name))).toEqual([]);
    for (const name of SERVER_ONLY_LUNABOT) if (!name.endsWith("_")) expect(boxEnvironmentAllows(name), name).toBe(false);
  });

  it("returns a fresh object, never the caller's", () => {
    const source = { PATH: "/usr/bin" };
    const kept = boxEnvironment(source);
    kept.PATH = "/changed";
    expect(source.PATH).toBe("/usr/bin");
  });
});
